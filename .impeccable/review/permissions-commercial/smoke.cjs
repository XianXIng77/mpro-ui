const { chromium } = require('C:/Users/XianXing/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const snap = name => page.screenshot({ path: `${__dirname}/${name}.png`, fullPage: true, animations: 'disabled' })
    const close = () => page.locator('.ant-drawer-close').click()
    const tab = label => page.getByRole('tab').filter({ hasText: label }).click()

    await page.goto('http://localhost:8080/#/permissions')
    await page.getByRole('heading', { name: '角色与权限', exact: true }).waitFor()
    assert.equal(await page.locator('.role-card').count(), 3)
    await snap('roles-desktop')
    await page.getByRole('button', { name: '站主权限', exact: true }).click()
    await page.getByText('站主拥有全部权限，角色模板不可修改。', { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: '保存授权', exact: true }).count(), 0)
    await close()

    await page.getByRole('button', { name: '普通用户权限', exact: true }).click()
    await page.getByRole('heading', { name: '页面与操作权限', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: '保存授权', exact: true }).isEnabled(), false)
    await page.getByRole('checkbox', { name: '新增邮箱', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: '保存授权', exact: true }).isEnabled(), true)
    await snap('role-drawer')
    await page.getByRole('button', { name: '撤销修改', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: '保存授权', exact: true }).isEnabled(), false)
    await close()

    await page.getByRole('button', { name: '查看普通用户成员', exact: true }).click()
    await page.getByRole('heading', { name: '成员与授权', exact: true }).waitFor()
    assert.equal(await page.locator('.members-table tbody tr.ant-table-row').count(), 4)
    await page.getByRole('button', { name: '重置筛选', exact: true }).click()
    assert.equal(await page.locator('.members-table tbody tr.ant-table-row').count(), 6)
    await snap('members-desktop')
    await page.getByRole('textbox', { name: '搜索成员', exact: true }).fill('不存在的成员')
    await page.getByText('没有匹配的成员，请调整搜索条件', { exact: true }).waitFor()
    await page.getByRole('button', { name: '重置筛选', exact: true }).click()
    await page.getByRole('button', { name: '管理许宁权限', exact: true }).click()
    await page.locator('.ant-collapse-content-active .grant-origin').first().waitFor()
    await snap('member-drawer')
    await close()

    await tab('访问策略')
    const policy = page.getByRole('switch', { name: '查询邮件详情', exact: true })
    const before = await policy.getAttribute('aria-checked')
    await policy.click()
    await page.waitForFunction(value => document.querySelector('[role="switch"][aria-label="查询邮件详情"]').getAttribute('aria-checked') !== value, before)
    await page.waitForFunction(() => !document.querySelector('[role="switch"][aria-label="查询邮件详情"]').disabled)
    await policy.click()
    await page.waitForFunction(value => document.querySelector('[role="switch"][aria-label="查询邮件详情"]').getAttribute('aria-checked') === value, before)
    await snap('policies-desktop')

    await page.getByRole('button', { name: '收起导航栏', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    await snap('policies-mobile')
    await tab('成员授权')
    await snap('members-mobile')
    await page.getByRole('button', { name: '管理林知行权限', exact: true }).click()
    await snap('drawer-mobile')
    await close()
    await tab('角色管理')
    await snap('roles-mobile')
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'document overflow')
    assert.ok(await page.locator('.permissions-page').evaluate(element => element.scrollWidth <= element.clientWidth + 1), 'permissions overflow')

    await page.evaluate(() => {
      const key = 'mpro.frontend.workspace.v1'
      const state = JSON.parse(localStorage.getItem(key))
      state.appearance.mode = 'dark'
      localStorage.setItem(key, JSON.stringify(state))
    })
    await page.setViewportSize({ width: 1440, height: 1080 })
    await page.reload()
    await page.locator('.workspace-page[data-theme="dark"]').waitFor()
    await snap('roles-dark')
    assert.deepEqual(errors, [])
    console.log('PASS: role cards, owner read-only, grant edit/reset, role filtering, search/empty state, inheritance, policy save roundtrip, mobile overflow, dark theme. No page errors.')
  } finally {
    await browser.close()
  }
})().catch(error => { console.error(error); process.exit(1) })
